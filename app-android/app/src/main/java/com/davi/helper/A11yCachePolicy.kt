package com.davi.helper

/**
 * 접근성 **노드 캐시**를 언제 끌지 정한다(#427 2단계).
 *
 * 캐시는 대상 앱이 쏘는 이벤트로만 무효화된다. 그 이벤트가 없는 앱에서는
 * `getRootInActiveWindow()`가 낡은 트리를 계속 돌려주므로 화면이 바뀌어도 우리가 못 본다 —
 * 2026-08-25 SM-S921N 실측: 코레일 인원 선택에서 인원을 다섯 번 올리는 동안 화면이 `5`인데
 * 서명은 153샘플(약 2분) 동안 옛 값 그대로였다.
 *
 * **그 앱이 이벤트를 아예 안 쏘는 것은 아니다.** 같은 날 220샘플 세션에서 코레일은
 * `WINDOW_CONTENT_CHANGED`를 77건 쐈는데 **전부 화면 전환에 몰려 있었고**(앱 진입 1건 ·
 * 인원 시트 열림 66건 · 시트 재배치 10건), **수량 `+`·`-` 탭에는 한 건도 없었다.**
 * 우리에게 필요한 무효화가 정확히 그 자리라 「쏜 적 있는 앱」이라는 판정으로는 못 잡는다.
 *
 * 그렇다고 늘 끌 수는 없다 — 끄면 노드 접근이 전부 IPC라 직렬화가 **23ms에서 800ms대**로 뛰고,
 * 그 값이 서비스 메인 스레드를 막는다.
 *
 * **판정은 「쏜 적 있는 앱」 집합이 아니라 침묵 카운터다**(PR #445 리뷰).
 * ① 집합이면 아직 아무 이벤트도 못 본 앱이 전부 「안 쏘는 앱」으로 분류돼, **앱 진입부터 첫
 * 조작까지** 캐시가 꺼진 채로 있다 — 시니어가 안내를 읽으며 머뭇거리는 바로 그 구간이다.
 * 증거 없이 최악을 가정하지 않는다.
 * ② 집합은 단조라 **다른 화면에서 자격 이벤트가 한 건만 와도** 그 앱이 영영 「쏘는 앱」이 되어
 * 153샘플 정지가 되살아난다. 카운터는 그 뒤 다시 조용해지면 스스로 되돌아온다.
 *
 * 상태는 서비스 메인 스레드에서만 만진다(접근성 콜백과 폴링이 같은 스레드다).
 */
class A11yCachePolicy(private val silenceSamples: Int = SILENCE_SAMPLES) {

    /** package별로, 마지막 자격 이벤트 이후 지나간 샘플 수. */
    private val samplesSinceEvent = mutableMapOf<String, Int>()

    /** 자격 이벤트를 봤다. 그 앱의 침묵을 처음부터 다시 센다. */
    fun onContentEvent(pkg: String) {
        samplesSinceEvent[pkg] = 0
    }

    /**
     * 샘플 하나를 관측했다. 캐시를 **켜 둬야 하면** true.
     *
     * [pkg]가 `null`이면(읽을 창이 없다) 켠다 — 낡을 트리 자체가 없고, 다음 앱이 우리가 보지도
     * 않은 앱의 판정을 물려받으면 안 된다.
     */
    fun onSample(pkg: String?): Boolean {
        if (pkg == null) return true
        val next = (samplesSinceEvent[pkg] ?: 0) + 1
        samplesSinceEvent[pkg] = next
        return next <= silenceSamples
    }

    /** 세션 지식이라 세션 전환에서 비운다. */
    fun reset() {
        samplesSinceEvent.clear()
    }

    companion object {
        /**
         * 이만큼 연속으로 자격 이벤트가 없어야 「안 쏘는 앱」으로 본다. 폴링이 약 0.75초라
         * 3초쯤이다 — 낡은 트리에 노출되는 구간을 그만큼으로 묶는다.
         *
         * 짧게 잡으면 이벤트가 뜸한 정상 앱에서 캐시가 껐다 켜졌다 하고, 길게 잡으면 노출
         * 구간이 길어진다. 코레일의 정지가 153샘플이었으므로 이 범위면 어느 쪽이든 그 함정을
         * 잡는다 — 첫 추정치다.
         */
        const val SILENCE_SAMPLES = 4
    }
}
