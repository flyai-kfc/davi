package com.davi.helper

/**
 * 다음 샘플까지의 지연을 정한다 — **미루기(디바운스)에 기한을 씌운다**(#380).
 *
 * 접근성 이벤트는 샘플을 미루면서 예약한다([GuideAccessibilityService.onAccessibilityEvent]).
 * 마지막 이벤트 뒤 `SETTLE_MS`가 지나야 화면을 떠서, 전환 직후 몰아치는 이벤트가 덜 그려진
 * 트리를 그대로 내보내지 않는다(#32). 그런데 이 규칙에는 **화면이 언젠가 조용해진다**는
 * 가정이 말없이 들어 있었다.
 *
 * 스스로 움직이는 화면은 조용해지지 않는다. 2026-08-23 SM-S921N 실측 — 배민 홈이 카운트다운
 * 타이머와 배너 캐러셀 때문에 `TYPE_WINDOW_CONTENT_CHANGED`를 **평균 36ms 간격**으로
 * (3041건/110초, 초당 28건꼴) 끊임없이 쏘았다. 이벤트마다 예약이 취소되고 350ms 뒤로 다시
 * 잡히니 샘플이 영원히 밀렸고, **110초 동안 폴링이 0회**였다. 그 구간에서 간격이 350ms를 넘은
 * 이벤트는 0건이다 — 최대값이 정확히 경계에 붙는 이 분포가 기아의 서명이다. 화면을 못 읽는
 * 동안 안내는 통째로 얼어붙는다: 조작도, 화면 전환도, 정체 알림도 감지되지 않는다.
 *
 * 아이러니는 이 폴링이 애초에 **이벤트에 의존하지 않으려고** 들어왔다는 것이다(#39 — 목록
 * 끝에서 스크롤 이벤트가 안 오는 문제). 구현에서는 그 이벤트가 폴링 시계를 계속 되감고 있었다.
 *
 * 그래서 미루되 **기한을 둔다.** 첫 예약이 기한을 열고, 뒤따르는 예약은 그 기한을 넘기지
 * 못한다. 조용한 화면에서는 [MAX_DEFER_MS]에 닿기 전에 샘플이 뜨므로 기존 동작 그대로다.
 */
class SampleSchedule(
    private val maxDeferMs: Long = MAX_DEFER_MS,
) {
    /** 열려 있는 기한. null이면 지금 예약된 샘플이 없다. */
    private var deadlineMs: Long? = null

    /**
     * [requestedMs] 뒤에 뜨고 싶다. 기한이 열려 있으면 거기까지로 줄여서 답한다.
     *
     * **첫 호출이 기한을 연다.** 기한의 기준점을 "폭주가 시작된 시점"이 아니라 "이번 예약
     * 사슬이 시작된 시점"으로 잡아야, 화면 꺼짐이나 세션 재시작으로 예약이 끊겼다 이어질 때
     * 이미 지난 기한을 읽어 settle 없이 곧바로 뜨는 일이 없다([reset] 참고).
     */
    fun delayFor(requestedMs: Long, nowMs: Long): Long {
        val deadline = deadlineMs ?: (nowMs + maxDeferMs).also { deadlineMs = it }
        return requestedMs.coerceAtMost((deadline - nowMs).coerceAtLeast(0L))
    }

    /**
     * 예약이 더는 살아 있지 않다 — 샘플이 실제로 떴거나, 예약을 걷었다. 다음 예약은 기한을
     * 새로 연다. **걷는 쪽에서 빠뜨리면** 남은 기한이 그사이 지나 버려, 되살아난 첫 예약이
     * 지연 0으로 계산돼 애니메이션 한복판을 뜬다.
     */
    fun reset() {
        deadlineMs = null
    }

    companion object {
        /**
         * 아무리 밀려도 이 시간 안에는 한 번 뜬다.
         *
         * `SETTLE_MS`(350ms)의 3.4배다 — 정상 전환의 이벤트 폭주는 이만큼 촘촘하게 이어지지
         * 않아 기한에 닿지 않는다(닿을 만큼 길어지면 #32가 되살아난다). 동시에 `POLL_MS`
         * (700ms)의 2배 아래로 둬서, 시끄러운 화면의 샘플 간격이 유휴 폴링보다 크게 느려지지
         * 않게 했다. 기한에 걸려 뜬 샘플이 애니메이션 중간을 잡더라도 [ScreenStabilityTracker]가
         * `HOLD_SAMPLES`만큼 같은 시그니처를 봐야 승격하므로 그 한 장으로 안내가 나가지 않는다.
         * 최악이 2회 × 1.2초라 `STUCK_AFTER_MS`(7초) 안쪽이며 정체 판정도 흔들지 않는다.
         */
        const val MAX_DEFER_MS = 1_200L
    }
}
