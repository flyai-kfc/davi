package com.davi.helper

/**
 * 기기에서 화면 텍스트를 서버로 보내기 전 치환하는 1차 개인정보 마스킹.
 *
 * 서버의 `server/app/masking.py`와 같은 순서·정규식을 유지한다. 규칙을 바꿀 때는
 * 반드시 양쪽을 함께 바꾸고 각각의 테스트를 갱신한다(SPEC §2, 이슈 #8).
 */
object PrivacyMasker {
    const val TOKEN = "•••"

    // 숫자 패턴의 경계를 `\b` 대신 **숫자 lookaround**로 본다(#312).
    //
    // JVM의 `\b`는 기본이 ASCII `\w` 기준이라 한글이 word character가 아니고, 그래서 1차는
    // 조사가 붙어도 걸렸다(#312에서 JVM으로 실측). 반면 파이썬 `re`의 `\b`는 유니코드
    // 인식이라 2차가 `'010-1234-5678에게'`를 놓쳤다 — **같은 정규식이 두 언어에서 다르게
    // 동작했다.** lookaround에는 그 차이가 없어 1차·2차가 같은 뜻이 된다.
    //
    // 오탐을 줄이기 위해 형태가 뚜렷한 것부터 적용한다. 서버와 순서도 같다.
    private val patterns = listOf(
        Regex("[A-Za-z0-9._%+\\-]+@[A-Za-z0-9.\\-]+\\.[A-Za-z]{2,}"),
        // MAC 주소(콜론 구분 6바이트 이상). 블루투스 기기 목록에서 그대로 새어 나갔다(#312 실측).
        // **경계에서 콜론을 금지하지 않는다** — 콜론은 `MAC:`·`주소:`처럼 앞 라벨의 구분자이기도
        // 해서, 금지하면 공백 없는 표기를 통째로 놓친다(PR #357 리뷰 실측). 7바이트 이상은
        // `{5,}`가 통째로 삼킨다. 하이픈 구분 형태는 넣지 않는다. 서버의 근거 주석과 같다.
        Regex("(?<![0-9A-Za-z])(?:[0-9A-Fa-f]{2}:){5,}[0-9A-Fa-f]{2}(?![0-9A-Za-z])"),
        // 주민등록번호 6-7
        Regex("(?<!\\d)\\d{6}[-\\s]?[1-4]\\d{6}(?!\\d)"),
        // 카드번호 4-4-4-4
        Regex("(?<!\\d)(?:\\d{4}[-\\s]?){3}\\d{4}(?!\\d)"),
        // 전화번호(휴대폰 위주). 하이픈/공백 허용.
        Regex("(?<!\\d)01[016789][-\\s]?\\d{3,4}[-\\s]?\\d{4}(?!\\d)"),
        // 계좌번호처럼 보이는 긴 숫자열(하이픈·공백 구분 세 덩어리).
        //
        // **날짜 모양을 먼저 거부한다**(#361). `2026-08-18`이 이 패턴에 들어맞아 가려졌다 —
        // 개인정보가 새는 게 아니라 안내 품질이 조용히 깎이는 쪽이라 아무도 빨개지지 않았다.
        // 달·일 범위까지 보므로 `12-34-56`처럼 날짜가 아닌 것은 계속 걸린다.
        // **첫 덩어리를 6자리까지 넓혔다** — 국민은행·우체국 형태가 통째로 새고 있었다.
        // 아는 한계와 맞바꿈은 서버 `masking.py`의 같은 자리에 적었다.
        // **정규식 문자열은 서버와 글자까지 같지만 "같은 뜻"까지는 아니다** — `\d`·`\s`가
        // 자바에서는 ASCII, 파이썬에서는 유니코드다. NBSP로 구분한 계좌나 전각 숫자는 서버
        // 2차만 잡는다. 여섯 패턴 전부에 걸린 옛 문제다(#312가 `\b`에서 같은 종류를 겪었다).
        Regex(
            "(?<!\\d)" +
                "(?!(?:\\d{4}|\\d{2})[-\\s](?:0?[1-9]|1[0-2])[-\\s](?:0?[1-9]|[12]\\d|3[01])(?!\\d))" +
                "\\d{2,6}[-\\s]\\d{2,6}[-\\s]\\d{2,7}(?!\\d)",
        ),
    )

    /** 빈 문자열은 그대로 두고, 일치한 개인정보 문자열은 하나의 토큰으로 치환한다. */
    fun maskText(text: String): String =
        patterns.fold(text) { masked, pattern -> pattern.replace(masked, TOKEN) }
}
